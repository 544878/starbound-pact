function make(templateId: string, name: string, index: number, five = false): Companion {
  const kit = FOUR_STAR_CHARACTERS.find((c) => c.id === templateId)!
  const pathIndex = COMBAT_PATHS.findIndex((p) => p.id === kit.mechanicPath)
  const path = COMBAT_PATHS[pathIndex]
  const profile = EXPANSION_HERO_PROFILES[name]

  return {
    id: five ? `R5-${String(index + 1).padStart(3, '0')}` : templateId,
    numericId: templateId,
    name,
    title: profile?.title ?? `${path.name}·${DUTY_LABELS[kit.slot]}`,
    rarity: five ? '5星' : '4星',
    role:
      kit.slot === 'tank'
        ? 'guardian'
        : kit.slot === 'healer' || kit.slot === 'specialist'
          ? 'support'
          : kit.slot === 'carry1'
            ? 'striker'
            : 'mystic',
    element: elements[pathIndex],
    gender: index % 2 ? 'male' : 'female',
    accent: colors[pathIndex],
    level: 1,
    constellation: 0,
    power: five ? 1000 : 950,
    artPosition: '0% 0%',
    realm: five ? '半神' : '主角团',
    path: path.id,
    adaptedPath: kit.compatible[0] ?? (path.id === 'inverse' ? 'mortal' : 'inverse'),
    faction: profile?.faction ?? `${path.name}行会`,
    persona: profile?.persona ?? `${path.name}修行者`,
    soulName: profile?.soulName ?? `${name}之誓`,
    weaponName: profile?.weaponName ?? `${name}·本命神兵`,
    vow: profile?.vow ?? `愿${path.name}之契，照亮我们的归途。`,
    skills: profile?.skills ?? [`${name}·起式`, `${path.name}·${DUTY_LABELS[kit.slot]}之契`],
    biography:
      profile?.biography ??
      `${name}在万界裂隙中选择与同行者并肩。以手中的兵锋，争取属于众生的明日。`,
    quotes: profile?.quotes ?? [`愿${path.name}之契，照亮我们的归途。`],
  }
}
